SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT DRUG_ID) AS UNIQUE_DRUGS
FROM RAW.RAW_DRUG;


SELECT COUNT(*) AS ORPHAN_MANUFACTURERS
FROM RAW.RAW_DRUG D
LEFT JOIN RAW.RAW_DRUG_MANUFACTURER M
    ON D.MANUFACTURER_ID = M.MANUFACTURER_ID
WHERE M.MANUFACTURER_ID IS NULL;


SELECT
    COUNT(*) AS TOTAL_MANUFACTURERS,
    COUNT(DISTINCT MANUFACTURER_ID) AS UNIQUE_MANUFACTURERS
FROM RAW.RAW_DRUG_MANUFACTURER;


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT DRUG_ID) AS UNIQUE_DRUGS,
    COUNT(DISTINCT DRUG_KEY) AS UNIQUE_DRUG_KEYS
FROM ANALYTICS.DIM_DRUG;


SELECT
    COUNT_IF(DRUG_NAME IS NULL) AS NULL_DRUG_NAMES,
    COUNT_IF(BRAND_NAME IS NULL) AS NULL_BRAND_NAMES,
    COUNT_IF(DRUG_CATEGORY IS NULL) AS NULL_CATEGORIES,
    COUNT_IF(UNIT_COST IS NULL) AS NULL_COSTS,
    COUNT_IF(MANUFACTURER_NAME IS NULL) AS NULL_MANUFACTURERS
FROM ANALYTICS.DIM_DRUG;

SELECT *
FROM ANALYTICS.DIM_DRUG
ORDER BY DRUG_KEY
LIMIT 10;


