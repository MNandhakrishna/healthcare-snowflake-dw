SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT DOCTOR_ID) AS UNIQUE_DOCTORS,
    COUNT(DISTINCT DOCTOR_KEY) AS UNIQUE_DOCTOR_KEYS
FROM ANALYTICS.DIM_DOCTOR;


SELECT COUNT(*) AS ORPHAN_DEPARTMENTS
FROM ANALYTICS.DIM_DOCTOR D
LEFT JOIN ANALYTICS.DIM_DEPARTMENT DP
    ON D.DEPARTMENT_ID = DP.DEPARTMENT_ID
WHERE DP.DEPARTMENT_ID IS NULL;

SELECT *
FROM ANALYTICS.DIM_DOCTOR
ORDER BY DOCTOR_KEY
LIMIT 10;

